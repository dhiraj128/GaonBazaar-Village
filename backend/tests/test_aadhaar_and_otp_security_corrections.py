@pytest.mark.asyncio
async def test_sec_04_cross_user_kyc_hijack_prevention(db_session):
    """Test SEC-4: User A cannot update User B's KYC profile (403 Forbidden)."""
    import secrets
    user_a_id = f"usr_a_{secrets.token_hex(4)}"
    user_b_id = f"usr_b_{secrets.token_hex(4)}"

    user_a = User(id=user_a_id, phone="9876540001", name="User A", role="vendor", is_active=True)
    user_b = User(id=user_b_id, phone="9876540002", name="User B", role="vendor", is_active=True)
    db_session.add_all([user_a, user_b])
    await db_session.commit()

    token_a = create_access_token({"sub": user_a_id, "phone": "9876540001", "role": "vendor"})

    qr_payload, _ = create_synthetic_signed_qr(name="User B Impersonation")

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as ac:
        # User A attempts to update User B's record
        res = await ac.post(
            "/api/v1/kyc/aadhaar/verify-qr",
            headers={"Authorization": f"Bearer {token_a}"},
            json={
                "qr_data": qr_payload,
                "user_id": user_b_id, # Attempting to overwrite User B!
                "role": "vendor",
                "consent_accepted": True
            }
        )
        assert res.status_code == 403
        assert "another user" in res.json()["detail"].lower()


