@pytest.mark.asyncio
async def test_sec_01_invalid_signature_rejection():
    """Test SEC-1: Tampered/invalid UIDAI signature is strictly rejected cryptographically."""
    store = UidaiCertificateStore.get_default()
    priv_key, _, _ = store.get_or_create_test_identity()

    fields = [
        "V2", "3", "548920210315123045001", "Genuine User", "01-01-1990", "M",
        "S/O Ram", "Muzaffarpur", "Near Park", "12", "Village", "843128", "SO", "Bihar",
        "Road", "Minapur", "Chaturshi", "9012"
    ]
    signed_data = b"".join(f.encode("iso-8859-1") + b"\xff" for f in fields)
    valid_sig = priv_key.sign(signed_data, padding.PKCS1v15(), hashes.SHA256())

    # Corrupt single byte of the signature
    corrupted_sig = bytearray(valid_sig)
    corrupted_sig[10] ^= 0xFF
    corrupted_payload = str(int.from_bytes(gzip.compress(signed_data + bytes(corrupted_sig)), "big"))

    parser = AadhaarSecureQrParser()
    with pytest.raises(InvalidAadhaarSignatureError):
        parser.parse_and_verify(corrupted_payload, allow_test_identity=True)


@pytest.mark.asyncio
async def test_sec_02_unknown_cert_signature_rejection():
    """Test SEC-2: Signature generated by an untrusted/unknown key is rejected."""
    untrusted_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    fields = [
        "V2", "3", "548920210315123045001", "Attacker Payload", "01-01-1990", "M",
        "S/O X", "Muzaffarpur", "Park", "1", "Village", "843128", "SO", "Bihar",
        "Road", "Minapur", "Chaturshi", "9012"
    ]
    signed_data = b"".join(f.encode("iso-8859-1") + b"\xff" for f in fields)
    untrusted_sig = untrusted_key.sign(signed_data, padding.PKCS1v15(), hashes.SHA256())
    payload = str(int.from_bytes(gzip.compress(signed_data + untrusted_sig), "big"))

    parser = AadhaarSecureQrParser()
    with pytest.raises(InvalidAadhaarSignatureError):
        parser.parse_and_verify(payload, allow_test_identity=True)


